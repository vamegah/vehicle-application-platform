#!/usr/bin/env python3
"""Generate the untracked platform/.env for local development (task 1.2). Python standard library only.

    python platform/scripts/init-env.py           # create platform/.env if it does not exist
    python platform/scripts/init-env.py --force   # replace it (then run `docker compose down -v`)

The file holds every local secret: database, Neo4j, Redis, Grafana and Vault dev tokens, the Garage RPC
secret and admin token, and the two Garage access key pairs (`legacy-integration` read-write on both
buckets, `data-readiness` read-only on the text bucket). The values are generated once and stay stable,
so the Vault dev server (in memory) is re-seeded with the same keys that Garage (persistent volume) holds.
Never commit platform/.env; platform/env.template lists the variable names only.
"""
from __future__ import annotations

import argparse
import os
import secrets
import sys
from pathlib import Path

PLATFORM = Path(__file__).resolve().parents[1]
ENV_FILE = PLATFORM / ".env"
TEMPLATE = PLATFORM / "env.template"


def garage_key_id() -> str:
    # Garage access key IDs are "GK" followed by 24 lowercase hex characters (12 bytes).
    return "GK" + secrets.token_hex(12)


def generate() -> dict[str, str]:
    return {
        # Hex only: a value starting with "-" or holding URL or shell metacharacters breaks some CLIs (for example
        # neo4j-admin reads a leading "-" as an option).
        "POSTGRES_PASSWORD": secrets.token_hex(24),
        "NEO4J_PASSWORD": secrets.token_hex(24),
        "REDIS_PASSWORD": secrets.token_hex(24),
        "GRAFANA_ADMIN_PASSWORD": secrets.token_hex(24),
        # Vault reserves the "hvs." prefix for tokens it issues; a custom dev root token ID must not use it.
        "VAULT_DEV_ROOT_TOKEN": "dev-root-" + secrets.token_hex(16),
        "GARAGE_RPC_SECRET": secrets.token_hex(32),
        "GARAGE_ADMIN_TOKEN": secrets.token_hex(32),
        "LEGACY_INTEGRATION_ACCESS_KEY_ID": garage_key_id(),
        "LEGACY_INTEGRATION_SECRET_ACCESS_KEY": secrets.token_hex(32),
        "DATA_READINESS_ACCESS_KEY_ID": garage_key_id(),
        "DATA_READINESS_SECRET_ACCESS_KEY": secrets.token_hex(32),
    }


def template_names() -> list[str]:
    names = []
    for line in TEMPLATE.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line and not line.startswith("#") and "=" in line:
            names.append(line.split("=", 1)[0].strip())
    return names


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--force", action="store_true", help="replace an existing platform/.env")
    args = parser.parse_args(argv)
    if ENV_FILE.exists() and not args.force:
        print(f"{ENV_FILE} exists; keeping it (use --force to replace it, then `docker compose down -v`)")
        return 0
    values = generate()
    names = template_names()
    if sorted(names) != sorted(values):
        print(f"init-env: {TEMPLATE.name} and the generator disagree: {sorted(set(names) ^ set(values))}", file=sys.stderr)
        return 1
    lines = ["# Generated by platform/scripts/init-env.py. Local development secrets. Never commit this file."]
    lines += [f"{name}={values[name]}" for name in names]
    ENV_FILE.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    if os.name != "nt":
        ENV_FILE.chmod(0o600)
    print(f"wrote {ENV_FILE} ({len(names)} variables)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
