"""Write the four ERP and MES golden files from golden/_erp_mes_bases.yaml (task 2.9).

contentHash and eventId of every valid sample are computed with erp_mes_rules.py, so the golden examples satisfy
the cross-field rules. Each golden file gets the topic's invalid cases plus the common ones.

    python contracts/tests/build_erp_mes_golden.py           # rewrite the four golden files
    python contracts/tests/build_erp_mes_golden.py --check   # exit 1 when a golden file is stale
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
import erp_mes_rules as rules  # noqa: E402

GOLDEN = Path(__file__).resolve().parent / "golden"
BASES = GOLDEN / "_erp_mes_bases.yaml"
HEADER = (
    "# GENERATED by contracts/tests/build_erp_mes_golden.py from golden/_erp_mes_bases.yaml. Do not edit by hand.\n"
    "# Golden examples for {topic} (task 2.9). contentHash and eventId of each valid sample follow erp_mes_rules.py.\n"
    "# All values are fictional.\n"
)
ENVELOPE_ORDER = ("eventId", "eventType", "version", "tenantId", "occurredAt", "sourceSystem", "naturalKey",
                  "contentHash", "extractedAt", "sourceRecordVersion", "payload")


def build() -> dict[str, str]:
    bases = yaml.safe_load(BASES.read_text(encoding="utf-8"))
    common = bases.pop("common_invalid")
    out = {}
    for topic in rules.TOPICS:
        spec = bases[topic]
        valid = {}
        for name, event in spec["valid"].items():
            done = rules.finalize(event)
            valid[name] = {k: done[k] for k in ENVELOPE_ORDER if k in done}
        first = next(iter(valid))
        invalid = list(spec["invalid"]) + [dict(m, base=first) for m in common]
        document = {"doc": f"{topic}.yaml", "message": spec["message"], "valid": valid, "invalid": invalid}
        out[topic] = HEADER.format(topic=topic) + yaml.safe_dump(document, sort_keys=False, allow_unicode=True, width=120)
    return out


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    stale = []
    for topic, text in build().items():
        path = GOLDEN / f"{topic}.yaml"
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8").replace("\r\n", "\n") != text:
                stale.append(path.name)
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {path.name}")
    if stale:
        print("stale golden files (run python contracts/tests/build_erp_mes_golden.py): " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
