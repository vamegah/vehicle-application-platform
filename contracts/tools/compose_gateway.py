"""Compose contracts/openapi/gateway.yaml from the per-context OpenAPI fragments (task 2.4).

gateway.yaml is the aggregate the API gateway exposes. It references every gateway-routed path item of the
per-context files with an external $ref, so a route is defined once, in its owning context's file. It omits
every path whose operations are all internal (x-internal-only: true): health probes, the sidecar, and
GET /admin/v1/layout-cache/{tenantId}. Admin routes come from admin.yaml only; the per-context references to
admin.yaml paths are skipped to avoid duplicates.

    python contracts/tools/compose_gateway.py           # rewrite gateway.yaml
    python contracts/tools/compose_gateway.py --check   # exit 1 when gateway.yaml is stale

The output is deterministic, so CI can fail on drift.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

OPENAPI_DIR = Path(__file__).resolve().parents[1] / "openapi"
GATEWAY = OPENAPI_DIR / "gateway.yaml"

# Gateway-routed sources, in output order. release-assurance-sidecar.yaml and audit-sink.yaml are internal only.
SOURCES = (
    "data-readiness.yaml",
    "legacy-integration.yaml",
    "integration-intelligence.yaml",
    "configuration-assurance.yaml",
    "release-assurance.yaml",
    "api-gateway.yaml",
    "admin.yaml",
)
HTTP_METHODS = ("get", "put", "post", "delete", "options", "head", "patch", "trace")

HEADER = """\
# GENERATED by contracts/tools/compose_gateway.py. Do not edit by hand: change the per-context file and
# re-run the tool. CI fails when this file differs from the tool output (task 2.4).
"""


def _load(name: str) -> dict:
    with (OPENAPI_DIR / name).open(encoding="utf-8") as fh:
        return yaml.safe_load(fh)


def _escape(path: str) -> str:
    return path.replace("~", "~0").replace("/", "~1")


def _resolve_path_item(source: str, item: dict) -> tuple[str, dict]:
    """Follow a whole-path-item $ref (one level is all the contracts use). Returns (file, path item)."""
    if set(item) == {"$ref"}:
        file_part, _, pointer = item["$ref"].partition("#")
        target = _load(file_part.lstrip("./")) if file_part else _load(source)
        node = target
        for part in [p for p in pointer.split("/") if p]:
            node = node[part.replace("~1", "/").replace("~0", "~")]
        return (file_part.lstrip("./") or source), node
    return source, item


def _all_internal(item: dict) -> bool:
    operations = [item[m] for m in HTTP_METHODS if m in item]
    return bool(operations) and all(op.get("x-internal-only") is True for op in operations)


def compose() -> str:
    paths: dict[str, dict] = {}
    tags: dict[str, dict] = {}
    for source in SOURCES:
        doc = _load(source)
        tag_defs = {t["name"]: t for t in doc.get("tags", [])}
        for path, item in (doc.get("paths") or {}).items():
            owner, resolved = _resolve_path_item(source, item)
            if owner != source or _all_internal(resolved):
                continue
            if path in paths:
                raise SystemExit(f"duplicate gateway route {path} in {source}")
            paths[path] = {"$ref": f"./{source}#/paths/{_escape(path)}"}
            for method in HTTP_METHODS:
                for tag in (resolved.get(method) or {}).get("tags", []):
                    tags.setdefault(tag, tag_defs.get(tag, {"name": tag}))
    document = {
        "openapi": "3.1.0",
        "info": {
            "title": "AutoReliance AI API gateway (aggregate)",
            "version": "1.0.0",
            "description": (
                "Every route the API gateway exposes, composed from the per-context contracts. Tenant routes are "
                "under /api/v1/<context>/ and gated by the tenant principal and its roles; operator routes are "
                "under /admin/v1/ and gated by the platform-operator role. Internal-only operations are not "
                "included. Errors are Problem Details; list endpoints use cursor pagination."
            ),
            "license": {"name": "Proprietary", "identifier": "LicenseRef-AutoReliance-Proprietary"},
        },
        "servers": [{"url": "https://gateway.autoreliance.example", "description": "API gateway"}],
        "tags": [tags[name] for name in tags],
        "security": [{"tenantPrincipal": []}],
        "paths": paths,
        "components": {
            "securitySchemes": {
                "tenantPrincipal": {"$ref": "./common/components.yaml#/components/securitySchemes/tenantPrincipal"},
                "platformOperator": {"$ref": "./common/components.yaml#/components/securitySchemes/platformOperator"},
            }
        },
    }
    return HEADER + yaml.safe_dump(document, sort_keys=False, allow_unicode=False, width=110)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when gateway.yaml is not up to date")
    args = parser.parse_args(argv)
    text = compose()
    if args.check:
        current = GATEWAY.read_text(encoding="utf-8") if GATEWAY.exists() else ""
        if current.replace("\r\n", "\n") != text:
            print("contracts/openapi/gateway.yaml is stale: run python contracts/tools/compose_gateway.py", file=sys.stderr)
            return 1
        print("gateway.yaml is up to date")
        return 0
    GATEWAY.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {GATEWAY.relative_to(OPENAPI_DIR.parent.parent)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
